"""Asynchronous Alert Persistence Engine for NIDS.

Provides a thread-safe, bounded-memory queue and background worker thread
to persist DetectionEvent records to SQLite asynchronously without blocking
the packet capture or detection pipeline.
"""

import logging
import queue
import threading
from typing import Any, Dict, Optional

from nids.detection.models import DetectionEvent
from nids.storage.alert_repository import AlertRepository

logger = logging.getLogger("nids.storage.async_writer")


class AsyncAlertWriter:
    """Bounded, asynchronous persistence worker for security detection events."""

    def __init__(
        self,
        repository: AlertRepository,
        max_queue_size: int = 5000,
        batch_timeout: float = 0.5,
    ):
        """Initialize asynchronous writer.

        Args:
            repository: AlertRepository instance managing SQLite writes.
            max_queue_size: Hard cap on memory buffer to prevent unbounded growth.
            batch_timeout: Polling timeout for worker loop in seconds.
        """
        self.repository = repository
        self.max_queue_size = max(1, int(max_queue_size))
        self.batch_timeout = float(batch_timeout)
        self._queue: queue.Queue[Optional[DetectionEvent]] = queue.Queue(maxsize=self.max_queue_size)
        self._stop_event = threading.Event()
        self._worker_thread: Optional[threading.Thread] = None
        self._lock = threading.Lock()

        # Telemetry metrics
        self.total_enqueued: int = 0
        self.total_persisted: int = 0
        self.total_dropped: int = 0
        self.total_errors: int = 0

    @property
    def is_running(self) -> bool:
        """Return True if background worker thread is active and running."""
        return self._worker_thread is not None and self._worker_thread.is_alive()

    def start(self) -> None:
        """Start the background persistence worker thread."""
        with self._lock:
            if self.is_running:
                return
            self._stop_event.clear()
            self._worker_thread = threading.Thread(
                target=self._worker_loop,
                name="AsyncAlertPersistenceWorker",
                daemon=True,
            )
            self._worker_thread.start()
            logger.info("Async alert persistence worker started.")

    def stop(self, timeout: float = 5.0) -> None:
        """Signal worker to stop, drain queue, and join thread."""
        with self._lock:
            if not self.is_running:
                return
            self._stop_event.set()
            try:
                self._queue.put_nowait(None)  # Sentinel to unblock queue get immediately
            except queue.Full:
                pass

        if self._worker_thread:
            self._worker_thread.join(timeout=timeout)
            with self._lock:
                self._worker_thread = None
        logger.info("Async alert persistence worker stopped.")

    def enqueue(self, event: DetectionEvent) -> bool:
        """Enqueue a DetectionEvent for background persistence without blocking.

        Args:
            event: DetectionEvent generated by DetectionEngine.

        Returns:
            bool: True if queued successfully, False if dropped due to capacity.
        """
        if event is None:
            return False

        # Lazily start worker if not explicitly started
        if not self.is_running and not self._stop_event.is_set():
            self.start()

        try:
            self._queue.put_nowait(event)
            with self._lock:
                self.total_enqueued += 1
            return True
        except queue.Full:
            with self._lock:
                self.total_dropped += 1
            logger.warning(
                "Persistence queue full (capacity %d). Dropped alert event: %s",
                self.max_queue_size,
                event.event_id,
            )
            return False

    def _worker_loop(self) -> None:
        """Main worker loop consuming events from the bounded queue."""
        while not self._stop_event.is_set():
            try:
                event = self._queue.get(timeout=self.batch_timeout)
            except queue.Empty:
                continue

            if event is None:
                self._queue.task_done()
                break

            self._persist_one(event)
            self._queue.task_done()

        # Drain any remaining items upon shutdown
        self._drain_remaining()

    def _persist_one(self, event: DetectionEvent) -> None:
        """Persist a single event with exception isolation."""
        try:
            self.repository.insert_detection_event(event)
            with self._lock:
                self.total_persisted += 1
        except Exception as err:
            with self._lock:
                self.total_errors += 1
            logger.error("Failed persisting alert event %s: %s", event.event_id, err)

    def _drain_remaining(self) -> None:
        """Drain and persist all remaining queued events before final shutdown."""
        while True:
            try:
                event = self._queue.get_nowait()
                if event is not None:
                    self._persist_one(event)
                self._queue.task_done()
            except queue.Empty:
                break

    def get_stats(self) -> Dict[str, Any]:
        """Return runtime telemetry of the asynchronous persistence worker."""
        with self._lock:
            return {
                "is_running": self.is_running,
                "queue_size": self._queue.qsize(),
                "max_queue_size": self.max_queue_size,
                "total_enqueued": self.total_enqueued,
                "total_persisted": self.total_persisted,
                "total_dropped": self.total_dropped,
                "total_errors": self.total_errors,
            }
