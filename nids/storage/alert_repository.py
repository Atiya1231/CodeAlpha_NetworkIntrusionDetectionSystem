"""Alert Repository for NIDS.

Provides CRUD operations, status management, filtering, and summary statistics
for security detection events stored in SQLite.
"""

import json
import logging
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional

from nids.detection.models import DetectionEvent
from nids.storage.database import Database

logger = logging.getLogger("nids.storage.alert_repository")


class AlertStatus(str, Enum):
    """Lifecycle statuses for security alerts."""
    NEW = "NEW"
    ACKNOWLEDGED = "ACKNOWLEDGED"
    RESOLVED = "RESOLVED"


class AlertRepository:
    """Manages persistent alert lifecycle, queries, and state transitions in SQLite."""

    def __init__(self, database: Database):
        """Initialize repository with database engine.

        Args:
            database: Database instance with connection pool and transaction support.
        """
        self.db = database

    def insert_detection_event(self, event: DetectionEvent) -> int:
        """Persist a DetectionEvent instance into SQLite.

        Args:
            event: DetectionEvent generated by DetectionEngine.

        Returns:
            int: Inserted alert row ID.
        """
        now_iso = datetime.now(timezone.utc).isoformat()
        evidence_str = json.dumps(event.evidence) if isinstance(event.evidence, dict) else str(event.evidence or "")

        src_port = None
        dst_port = None
        if isinstance(event.evidence, dict):
            src_port = event.evidence.get("source_port") or event.evidence.get("src_port")
            dst_port = event.evidence.get("destination_port") or event.evidence.get("dest_port")

        data = {
            "event_id": event.event_id,
            "rule_id": event.rule_id,
            "title": event.detection_name,
            "severity": event.severity.value,
            "source_ip": event.source_ip,
            "source_port": src_port,
            "destination_ip": event.destination_ip,
            "destination_port": dst_port,
            "protocol": event.protocol or "UNKNOWN",
            "timestamp": event.timestamp_iso,
            "description": event.description,
            "evidence": evidence_str,
            "raw_evidence": evidence_str,
            "threshold_used": str(event.threshold_used),
            "confidence": event.confidence,
            "deduplication_key": event.deduplication_key,
            "status": AlertStatus.NEW.value,
            "created_at": now_iso,
            "updated_at": now_iso,
        }
        return self.insert_alert(data)

    def insert_alert(self, alert_data: Dict[str, Any]) -> int:
        """Insert an alert dictionary with backward-compatible field handling.

        Args:
            alert_data: Dictionary of alert fields.

        Returns:
            int: Inserted alert row ID.
        """
        now_iso = datetime.now(timezone.utc).isoformat()

        # Handle evidence serialization
        evidence_raw = alert_data.get("evidence") or alert_data.get("raw_evidence")
        if isinstance(evidence_raw, dict):
            evidence_str = json.dumps(evidence_raw)
        else:
            evidence_str = str(evidence_raw or "")

        rec_action = alert_data.get("recommended_action")
        if not rec_action:
            try:
                from nids.response.recommendations import get_recommended_response
                evidence_obj = alert_data.get("evidence") or alert_data.get("raw_evidence")
                if isinstance(evidence_obj, str):
                    try:
                        evidence_obj = json.loads(evidence_obj)
                    except Exception:
                        evidence_obj = {}
                rec = get_recommended_response(
                    rule_id=alert_data.get("rule_id"),
                    title=alert_data.get("title"),
                    severity=alert_data.get("severity"),
                    evidence=evidence_obj if isinstance(evidence_obj, dict) else {},
                    source_ip=alert_data.get("source_ip"),
                )
                rec_action = rec.recommended_action
            except Exception:
                rec_action = "Investigate alert telemetry and verify host integrity."

        query = """
        INSERT INTO alerts (
            event_id, rule_id, title, severity, source_ip, source_port,
            destination_ip, destination_port, protocol, timestamp, description,
            raw_evidence, evidence, threshold_used, confidence, deduplication_key,
            status, created_at, updated_at, acknowledged_at, resolved_at,
            recommended_action, response_notes, responder
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """
        params = (
            alert_data.get("event_id"),
            alert_data.get("rule_id"),
            alert_data.get("title") or "Unnamed Security Alert",
            (alert_data.get("severity") or "INFO").upper(),
            alert_data.get("source_ip") or "",
            alert_data.get("source_port"),
            alert_data.get("destination_ip") or "",
            alert_data.get("destination_port"),
            alert_data.get("protocol") or "UNKNOWN",
            alert_data.get("timestamp") or now_iso,
            alert_data.get("description") or "",
            evidence_str,
            evidence_str,
            str(alert_data.get("threshold_used") or ""),
            alert_data.get("confidence") or "HEURISTIC_INDICATOR",
            alert_data.get("deduplication_key") or "",
            alert_data.get("status") or AlertStatus.NEW.value,
            alert_data.get("created_at") or now_iso,
            alert_data.get("updated_at") or now_iso,
            alert_data.get("acknowledged_at"),
            alert_data.get("resolved_at"),
            rec_action,
            alert_data.get("response_notes"),
            alert_data.get("responder"),
        )

        with self.db.transaction() as conn:
            cursor = conn.execute(query, params)
            return cursor.lastrowid or 0

    def get_alert_by_id(self, alert_id: int) -> Optional[Dict[str, Any]]:
        """Retrieve single alert by its primary key ID."""
        query = "SELECT * FROM alerts WHERE id = ?"
        with self.db.connection() as conn:
            cursor = conn.execute(query, (alert_id,))
            row = cursor.fetchone()
            return self._format_row(row) if row else None

    def get_alert_by_event_id(self, event_id: str) -> Optional[Dict[str, Any]]:
        """Retrieve single alert by unique DetectionEvent ID."""
        query = "SELECT * FROM alerts WHERE event_id = ?"
        with self.db.connection() as conn:
            cursor = conn.execute(query, (event_id,))
            row = cursor.fetchone()
            return self._format_row(row) if row else None

    def _build_filter_clause(
        self,
        severity: Optional[str] = None,
        status: Optional[str] = None,
        rule_id: Optional[str] = None,
        source_ip: Optional[str] = None,
        destination_ip: Optional[str] = None,
        start_date: Optional[str] = None,
        end_date: Optional[str] = None,
        confidence: Optional[str] = None,
    ) -> tuple[str, List[Any]]:
        """Construct parameterized SQL WHERE clause for alert filtering."""
        query_parts = ["WHERE 1=1"]
        params: List[Any] = []

        if severity:
            query_parts.append("AND UPPER(severity) = ?")
            params.append(severity.strip().upper())

        if status:
            query_parts.append("AND UPPER(status) = ?")
            params.append(status.strip().upper())

        if rule_id:
            query_parts.append("AND rule_id = ?")
            params.append(rule_id.strip())

        if confidence:
            query_parts.append("AND confidence = ?")
            params.append(confidence.strip())

        if source_ip:
            query_parts.append("AND source_ip = ?")
            params.append(source_ip.strip())

        if destination_ip:
            query_parts.append("AND destination_ip = ?")
            params.append(destination_ip.strip())

        if start_date:
            query_parts.append("AND timestamp >= ?")
            params.append(start_date.strip())

        if end_date:
            ed = end_date.strip()
            # If date only (YYYY-MM-DD), extend to end of the day
            if len(ed) == 10:
                ed = f"{ed}T23:59:59.999999"
            query_parts.append("AND timestamp <= ?")
            params.append(ed)

        return " ".join(query_parts), params

    def count_alerts(
        self,
        severity: Optional[str] = None,
        status: Optional[str] = None,
        rule_id: Optional[str] = None,
        source_ip: Optional[str] = None,
        destination_ip: Optional[str] = None,
        start_date: Optional[str] = None,
        end_date: Optional[str] = None,
        confidence: Optional[str] = None,
    ) -> int:
        """Return total count of alerts matching the provided filters."""
        where_clause, params = self._build_filter_clause(
            severity=severity,
            status=status,
            rule_id=rule_id,
            source_ip=source_ip,
            destination_ip=destination_ip,
            start_date=start_date,
            end_date=end_date,
            confidence=confidence,
        )
        query = f"SELECT COUNT(*) as total FROM alerts {where_clause}"
        with self.db.connection() as conn:
            cursor = conn.execute(query, tuple(params))
            row = cursor.fetchone()
            return row["total"] if row else 0

    def get_recent_alerts(
        self,
        limit: int = 50,
        offset: int = 0,
        severity: Optional[str] = None,
        status: Optional[str] = None,
        rule_id: Optional[str] = None,
        source_ip: Optional[str] = None,
        destination_ip: Optional[str] = None,
        start_date: Optional[str] = None,
        end_date: Optional[str] = None,
        confidence: Optional[str] = None,
    ) -> List[Dict[str, Any]]:
        """Retrieve paginated list of alerts with comprehensive filter support."""
        where_clause, params = self._build_filter_clause(
            severity=severity,
            status=status,
            rule_id=rule_id,
            source_ip=source_ip,
            destination_ip=destination_ip,
            start_date=start_date,
            end_date=end_date,
            confidence=confidence,
        )

        query = f"SELECT * FROM alerts {where_clause} ORDER BY id DESC LIMIT ? OFFSET ?"
        params.extend([max(1, limit), max(0, offset)])

        with self.db.connection() as conn:
            cursor = conn.execute(query, tuple(params))
            return [self._format_row(row) for row in cursor.fetchall()]

    def update_alert_status(
        self,
        alert_id: int,
        new_status: str,
        timestamp: Optional[str] = None,
        notes: Optional[str] = None,
        responder: Optional[str] = None,
    ) -> bool:
        """Update alert lifecycle status to NEW, ACKNOWLEDGED, or RESOLVED.

        Enforces valid state transition matrix:
        - NEW -> ACKNOWLEDGED
        - NEW -> RESOLVED
        - ACKNOWLEDGED -> RESOLVED
        - Duplicate same-state updates are treated as idempotent no-ops.
        - RESOLVED -> any other state is strictly prohibited.
        - ACKNOWLEDGED -> NEW is strictly prohibited.

        Args:
            alert_id: Primary key of alert.
            new_status: Valid AlertStatus value.
            timestamp: Optional ISO timestamp override.
            notes: Optional analyst resolution / investigation notes.
            responder: Optional analyst identifier.

        Returns:
            bool: True if alert was updated, False if alert not found.

        Raises:
            ValueError: If status is invalid or if the transition is prohibited.
        """
        valid_statuses = {s.value for s in AlertStatus}
        status_upper = new_status.strip().upper()
        if status_upper not in valid_statuses:
            raise ValueError(f"Invalid alert status: '{new_status}'. Allowed: {sorted(valid_statuses)}")

        existing = self.get_alert_by_id(alert_id)
        if not existing:
            return False

        current_status = existing["status"].upper()

        # Idempotent no-op (unless notes or responder are being updated)
        if current_status == status_upper and notes is None and responder is None:
            return True

        # Enforce valid lifecycle state transitions
        if current_status == AlertStatus.RESOLVED.value and status_upper != AlertStatus.RESOLVED.value:
            raise ValueError(
                f"Cannot transition alert from '{current_status}' to '{status_upper}' (alert is already resolved)"
            )

        if current_status == AlertStatus.ACKNOWLEDGED.value and status_upper == AlertStatus.NEW.value:
            raise ValueError(
                f"Cannot transition alert from '{current_status}' to '{status_upper}' (reopening acknowledged alert to NEW is prohibited)"
            )

        now_iso = timestamp or datetime.now(timezone.utc).isoformat()

        set_clauses = ["status = ?", "updated_at = ?"]
        params: List[Any] = [status_upper, now_iso]

        if status_upper == AlertStatus.ACKNOWLEDGED.value:
            set_clauses.append("acknowledged_at = ?")
            params.append(now_iso)
        elif status_upper == AlertStatus.RESOLVED.value:
            set_clauses.append("resolved_at = ?")
            params.append(now_iso)

        if notes is not None:
            set_clauses.append("response_notes = ?")
            params.append(notes)
        if responder is not None:
            set_clauses.append("responder = ?")
            params.append(responder)

        params.append(alert_id)
        query = f"UPDATE alerts SET {', '.join(set_clauses)} WHERE id = ?"

        with self.db.transaction() as conn:
            cursor = conn.execute(query, tuple(params))
            return cursor.rowcount > 0

    def get_alert_statistics(self) -> Dict[str, Any]:
        """Return comprehensive alert statistics grouped by status, severity, and rule."""
        stats: Dict[str, Any] = {
            "total_alerts": 0,
            "new_alerts": 0,
            "acknowledged_alerts": 0,
            "resolved_alerts": 0,
            "severity_counts": {
                "CRITICAL": 0,
                "HIGH": 0,
                "MEDIUM": 0,
                "LOW": 0,
                "INFO": 0,
            },
            "rule_counts": {},
        }

        with self.db.connection() as conn:
            # Total count
            cur_tot = conn.execute("SELECT COUNT(*) as total FROM alerts")
            row_tot = cur_tot.fetchone()
            stats["total_alerts"] = row_tot["total"] if row_tot else 0

            # Status counts
            cur_stat = conn.execute("SELECT UPPER(status) as st, COUNT(*) as cnt FROM alerts GROUP BY UPPER(status)")
            for row in cur_stat.fetchall():
                st = row["st"]
                cnt = row["cnt"]
                if st == "NEW":
                    stats["new_alerts"] = cnt
                elif st == "ACKNOWLEDGED":
                    stats["acknowledged_alerts"] = cnt
                elif st == "RESOLVED":
                    stats["resolved_alerts"] = cnt

            # Severity counts
            cur_sev = conn.execute("SELECT UPPER(severity) as sev, COUNT(*) as cnt FROM alerts GROUP BY UPPER(severity)")
            for row in cur_sev.fetchall():
                sev = row["sev"]
                if sev in stats["severity_counts"]:
                    stats["severity_counts"][sev] = row["cnt"]

            # Rule counts
            cur_rule = conn.execute(
                "SELECT rule_id, COUNT(*) as cnt FROM alerts WHERE rule_id IS NOT NULL AND rule_id != '' GROUP BY rule_id"
            )
            for row in cur_rule.fetchall():
                stats["rule_counts"][row["rule_id"]] = row["cnt"]

        return stats

    def get_alert_summary(self) -> Dict[str, Any]:
        """Return counts of alerts grouped by severity level and status."""
        summary: Dict[str, Any] = {
            "CRITICAL": 0,
            "HIGH": 0,
            "MEDIUM": 0,
            "LOW": 0,
            "INFO": 0,
            "status_counts": {
                "NEW": 0,
                "ACKNOWLEDGED": 0,
                "RESOLVED": 0,
            },
            "total_alerts": 0,
            "rule_counts": {},
        }

        stats = self.get_alert_statistics()
        summary["total_alerts"] = stats["total_alerts"]
        summary["status_counts"]["NEW"] = stats["new_alerts"]
        summary["status_counts"]["ACKNOWLEDGED"] = stats["acknowledged_alerts"]
        summary["status_counts"]["RESOLVED"] = stats["resolved_alerts"]
        for sev, count in stats["severity_counts"].items():
            summary[sev] = count
        summary["rule_counts"] = stats["rule_counts"]

        return summary

    def _format_row(self, row: Any) -> Dict[str, Any]:
        """Convert SQLite Row to dictionary and safely parse JSON evidence if present."""
        d = dict(row)

        # Parse evidence JSON if valid
        evidence_str = d.get("evidence") or d.get("raw_evidence")
        if evidence_str:
            try:
                d["evidence_parsed"] = json.loads(evidence_str)
            except Exception:
                d["evidence_parsed"] = None

        # Ensure recommended_action and recommended_response are populated
        try:
            from nids.response.recommendations import get_recommended_response
            rec = get_recommended_response(
                rule_id=d.get("rule_id"),
                title=d.get("title"),
                severity=d.get("severity"),
                evidence=d.get("evidence_parsed"),
                source_ip=d.get("source_ip"),
            )
            if not d.get("recommended_action"):
                d["recommended_action"] = rec.recommended_action
            d["recommended_response"] = rec.to_dict()
        except Exception:
            if not d.get("recommended_action"):
                d["recommended_action"] = "Investigate alert telemetry and verify host integrity."

        return d
